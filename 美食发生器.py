# 内脏类关键词：抽到就跳过（双保险）
BANNED = ("肠", "肚", "腰", "肝", "肺", "血", "百叶", "黄喉", "脑", "胗", "杂", "蹄筋", "肾", "胰")


def clean(dish: str) -> bool:
    return not any(k in dish for k in BANNED)


def pick(cuisine=None, used=None):
    names = [cuisine] if cuisine else list(DISHES)
    for _ in range(80):
        c = random.choice(names)
        pool = [d for d in DISHES[c]
                if clean(d) and (used is None or (c, d) not in used)]
        if pool:
            return c, random.choice(pool)
    # 这一轮全抽过了，清空重来
    if used is not None:
        used.clear()
        return pick(cuisine, used)
    return random.choice(names), DISHES[names[0]][0]


def main() -> None:
    arg = sys.argv[1] if len(sys.argv) > 1 else None
    if arg in ("列表", "list"):
        total = 0
        for c, ds in DISHES.items():
            ok = [d for d in ds if clean(d)]
            total += len(ok)
            print(f"{c}: {len(ok)} 道")
        print(f"合计 {total} 道")
        return
    if arg and arg not in DISHES:
        print(f"没有「{arg}」这个菜系。可选：{'、'.join(DISHES)}")
        return

    print("美食发生器：按回车来一道，输入 q 退出。\n")
    n = 0
    used = set()
    while True:
        c, d = pick(arg, used)
        used.add((c, d))
        n += 1
        print(f"  第 {n} 道 · [{c}] {d}")
        cmd = input().strip().lower()
        if cmd == "q":
            print("收工，去做饭吧。")
            break


if __name__ == "__main__":
    main()
